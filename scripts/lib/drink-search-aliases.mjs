function normalizeText(text) {
  return (text || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/\bcafe\b/g, "ca phe")
    .trim();
}

export function getDrinkSearchAliases(drinkName) {
  if (!drinkName) return [];
  const trimmed = drinkName.trim();

  if (DRINK_SEARCH_ALIASES[trimmed]) {
    return DRINK_SEARCH_ALIASES[trimmed];
  }

  const normTarget = normalizeText(trimmed);
  for (const [key, aliases] of Object.entries(DRINK_SEARCH_ALIASES)) {
    if (normalizeText(key) === normTarget) {
      return aliases;
    }
  }

  return [trimmed];
}
